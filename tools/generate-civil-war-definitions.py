#!/usr/bin/env python3
"""Generate Civil War / Synthezoid encounter definitions from the local card index.

This reads metadata only. Entity handlers implement card behavior separately.
No network access or image processing is involved.
"""
import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / 'src/Marvel/CivilWar/Cards.hs'
SET_NAMES = {
    'iron_man_leader': 'CwIronMan', 'captain_marvel_leader': 'CwCaptainMarvel',
    'captain_america_leader': 'CwCaptainAmerica', 'spider_woman_leader': 'CwSpiderWoman',
    'she_hulk_leader': 'CwSheHulk', 'vision_leader': 'CwVision',
    'registration': 'CwRegistration', 'resistance': 'CwResistance',
    'synthezoid_registration': 'CwSynthezoidRegistration',
    'synthezoid_resistance': 'CwSynthezoidResistance', 'standard_pvp': 'CwStandardPvp',
}
TRAITS = {'S.H.I.E.L.D.': 'Shield', 'Young Avenger': 'YoungAvenger'}
STANDARD_ALIASES = {
    **{str(code): '56125' for code in [56203, 57036, 57078]},
    **{str(code): '56126' for code in [56204, 57037, 57079]},
    **{str(code): '56127' for code in [56205, 57038, 57080]},
    **{f'{code}{face}': f'56128{face}' for code in [56206, 57039, 57081] for face in 'ab'},
}


def constructor(text):
    return ''.join(part[:1].upper() + part[1:] for part in re.split(r'[^A-Za-z0-9]+', text) if part)


def trait(text):
    return TRAITS.get(text, constructor(text))


def set_name(code):
    return SET_NAMES.get(code, 'Cw' + constructor(code))


def quote(text):
    return json.dumps(text, ensure_ascii=False)


def game_value(n, fixed):
    return f'GV.{"Static" if fixed else "PerPlayer"} {n or 0}'


def keywords(card):
    text = re.sub(r'<[^>]*>', '', card.get('text', '')).strip()
    found = []
    simple = ['Toughness', 'Guard', 'Quickstrike', 'Villainous', 'Steady', 'Stalwart',
              'Ranged', 'Piercing', 'Surge', 'Peril', 'Permanent']
    while text:
        match = re.match(r'(' + '|'.join(simple) + r')\b[.,]?\s*', text, re.I)
        if match:
            found.append('K.' + next(k for k in simple if k.lower() == match[1].lower()))
        else:
            match = re.match(r'(Retaliate|Incite|Victory|Hinder)\s+(\d+)(\[per_hero\])?[.,]?\s*', text, re.I)
            if match:
                key = match[1].capitalize()
                value = f'({game_value(int(match[2]), not bool(match[3]))})' if key == 'Hinder' else match[2]
                found.append(f'K.{key} {value}')
            else:
                match = re.match(r'Teamwork\s*\(([^)]+)\)[.,]?\s*', text, re.I)
                if match:
                    found.append(f'K.Teamwork T.{trait(match[1])}')
                elif text.lower().startswith('mass form.'):
                    found.append('K.MassForm')
                    text = text[len('mass form.'):].strip()
                    continue
                else:
                    break
        text = text[match.end():]
    if card.get('permanent') and 'K.Permanent' not in found:
        found.append('K.Permanent')
    return found


def main():
    cards = [c for c in json.loads((ROOT / 'frontend/public/data/cards.json').read_text())['cards']
             if c.get('packCode') in ['cw', 'synthezoid'] and c.get('faction') == 'encounter'
             and (c['packCode'] != 'cw' or int(c['code'][:5]) >= 56059)]
    cards.sort(key=lambda c: c['code'])
    by_code = {c['code']: c for c in cards}
    type_names = {'leader': 'VillainType', 'main_scheme': 'MainSchemeType',
                  'side_scheme': 'SideSchemeType', 'attachment': 'AttachmentType',
                  'treachery': 'TreacheryType', 'minion': 'MinionType', 'obligation': 'ObligationType'}
    lines = ['-- Generated by tools/generate-civil-war-definitions.py; edit the local card data.',
             'module Marvel.CivilWar.Cards where', '', 'import Marvel.Prelude',
             'import Marvel.Card.Def', 'import Marvel.Boost', 'import Marvel.Cost.Types',
             'import Marvel.Criteria', 'import Marvel.EncounterSet',
             'import Marvel.GameValue.Types qualified as GV', 'import Marvel.Keyword qualified as K',
             'import Marvel.Trait.Types qualified as T', '']
    base = (ROOT / 'src/Marvel/CampaignPlayers/EncounterCards.hs').read_text()
    base = base[base.index('nemesisCard ::'):base.index('\nenc56023 ::')]
    lines += [base.replace('nemesisCard', 'civilWarCard').rstrip(), '']
    for card in cards:
        code = card['code']
        qty = card.get('quantity', 1)
        if card['type'] in ['leader', 'main_scheme'] or code in STANDARD_ALIASES or card.get('hidden'):
            qty = None
        boosts = ['Boost'] * card.get('boost', 0) + ['Star'] * bool(card.get('boostStar'))
        name = quote(card['name'])
        if card.get('subname'):
            # Name's constructor preserves the printed subtitle.
            name = f'Name {name} (Just {quote(card["subname"])})'
        lines += [f'cw{code} :: CardDef', f'cw{code} = civilWarCard',
                  f'  {{ cdCardCode = {quote(code)}, cdName = {name}',
                  f'  , cdCardType = {type_names[card["type"]]}, cdTraits = fromList [{", ".join("T." + trait(t) for t in card.get("traits", []))}]',
                  f'  , cdUnique = {card.get("unique", False)}, cdBoostIcons = [{", ".join(boosts)}]',
                  f'  , cdKeywords = fromList [{", ".join(keywords(card))}]',
                  f'  , cdEncounterSet = Just {set_name(card["setCode"])}, cdEncounterSetQuantity = {"Nothing" if qty is None else "Just " + str(qty)}',
                  f'  , cdHazards = {card.get("hazard", 0)}, cdAcceleration = {card.get("acceleration", 0)}, cdAmplify = {card.get("amplify", 0)}', '  }', '']
    lines += ['civilWarDefinitions :: [CardDef]', 'civilWarDefinitions =',
              '  [ ' + '\n  , '.join('cw' + c['code'] for c in cards) + '\n  ]', '',
              'canonicalCode :: CardCode -> CardCode', 'canonicalCode code = case code of']
    lines += [f'  {quote(code)} -> {quote(canonical)}' for code, canonical in sorted(STANDARD_ALIASES.items())]
    lines += ['  _ -> code', '', 'printedMinionStats :: CardCode -> (Natural, Natural, Natural)',
              'printedMinionStats code = case code of']
    for c in cards:
        if c['type'] == 'minion':
            assert not c.get('healthPerHero'), c['code']
            lines.append(f'  {quote(c["code"])} -> ({c.get("scheme", 0)}, {c.get("attack", 0)}, {c["health"]})')
    lines += ['  _ -> error "Unknown Civil War minion stats"', '',
              'printedLeaderStats :: CardCode -> (Natural, Natural, Int, Natural)', 'printedLeaderStats code = case code of']
    for c in cards:
        if c['type'] == 'leader':
            assert c.get('healthPerHero'), c['code']
            stage = ['I', 'II', 'III', 'IV'].index(c['stage']) + 1
            lines.append(f'  {quote(c["code"])} -> ({c.get("scheme", 0)}, {c.get("attack", 0)}, {c["health"]}, {stage})')
    lines += ['  _ -> error "Unknown Civil War leader stats"', '',
              'printedSchemeStats :: CardCode -> (GV.GameValue, GV.GameValue, GV.GameValue)', 'printedSchemeStats code = case code of']
    for c in cards:
        if c['type'] == 'main_scheme':
            face = by_code[c['linkedTo']] if c.get('stage', '').endswith('A') else c
            vals = [game_value(face.get(key, 0), face.get(fixed, False)) for key, fixed in
                    [('threat', 'threatFixed'), ('baseThreat', 'baseThreatFixed'), ('escalationThreat', 'escalationThreatFixed')]]
            lines.append(f'  {quote(c["code"])} -> ({", ".join(vals)})')
    lines += ['  _ -> error "Unknown Civil War scheme stats"', '',
              'printedSideSchemeThreat :: CardCode -> GV.GameValue', 'printedSideSchemeThreat code = case code of']
    for c in cards:
        if c['type'] == 'side_scheme':
            lines.append(f'  {quote(c["code"])} -> {game_value(c.get("baseThreat", 0), c.get("baseThreatFixed", False))}')
    lines += ['  _ -> error "Unknown Civil War side scheme threat"', '']
    # CardCode is imported explicitly: Card.Def does not re-export its own imports.
    lines.insert(lines.index('import Marvel.Card.Def') + 1, 'import Marvel.Card.Code')
    if any(c.get('subname') for c in cards):
        lines.insert(lines.index('import Marvel.Card.Def') + 1, 'import Marvel.Name')
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text('\n'.join(lines))
    sets = sorted({set_name(c['setCode']) for c in cards})
    print(f'Generated {len(cards)} encounter faces across {len(sets)} sets.')
    print('EncounterSet constructors: ' + ', '.join(sets))


if __name__ == '__main__':
    main()
