#!/usr/bin/env python3
"""Write src/Marvel/Card/WhenDefeated.hs from frontend/public/data/cards.json: the
cards whose text has a When Defeated ability, so the engine asks before resolving it.

usage: tools/generate-when-defeated.py   (after tools/generate-cards.py)
"""
import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
CARDS = ROOT / "frontend" / "public" / "data" / "cards.json"
OUT = ROOT / "src" / "Marvel" / "Card" / "WhenDefeated.hs"
TYPES = {"minion", "side_scheme", "villain", "ally"}

cards = json.loads(CARDS.read_text())["cards"]
ability_label = re.compile(r"<b>\s*When Defeated\s*(?:</b>\s*:|:\s*</b>)", re.IGNORECASE)
codes = sorted(c["code"] for c in cards if c.get("type") in TYPES and ability_label.search(c.get("text") or ""))
body = "\n".join(f'    {"[" if i == 0 else ","} "{code}"' for i, code in enumerate(codes))
OUT.write_text(f'''-- | Generated by tools/generate-when-defeated.py from the card text: do not edit.
module Marvel.Card.WhenDefeated (hasWhenDefeated) where

import Marvel.Prelude

import Data.HashSet qualified as HashSet
import Marvel.Card.Code

-- | Whether the card has a When Defeated
-- ability.
hasWhenDefeated :: CardCode -> Bool
hasWhenDefeated = (`HashSet.member` codes)

codes :: HashSet CardCode
codes =
  HashSet.fromList
{body}
    ]
''')
print(f"wrote {len(codes)} codes to {OUT}")
