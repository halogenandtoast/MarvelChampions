#!/usr/bin/env python3
"""Generate printed attachment Hero Action/Response metadata for Sunfire."""
import json
import re
from pathlib import Path
ROOT = Path(__file__).resolve().parent.parent
cards = json.loads((ROOT / 'frontend/public/data/cards.json').read_text())['cards']
codes = sorted(c['code'] for c in cards if c.get('type') == 'attachment' and re.search(r'Hero (?:Action|Response)', c.get('text') or ''))
body = '\n'.join(f'    {"[" if i == 0 else ","} "{code}"' for i, code in enumerate(codes))
(ROOT / 'src/Marvel/Card/AttachmentHeroAbilities.hs').write_text('''-- | Generated by tools/generate-attachment-hero-abilities.py from printed card text.
module Marvel.Card.AttachmentHeroAbilities (hasPrintedHeroActionOrResponse) where

import Marvel.Prelude
import Data.HashSet qualified as HashSet
import Marvel.Card.Code

hasPrintedHeroActionOrResponse :: CardCode -> Bool
hasPrintedHeroActionOrResponse = (`HashSet.member` codes)

codes :: HashSet CardCode
codes = HashSet.fromList
''' + body + '\n    ]\n')
