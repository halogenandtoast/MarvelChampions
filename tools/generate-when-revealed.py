#!/usr/bin/env python3
"""Write src/Marvel/Card/WhenRevealed.hs from frontend/public/data/cards.json: the
encounter cards, other than treacheries (each of which is all When Revealed), whose text
has a When Revealed ability, so the engine asks before resolving it.

usage: tools/generate-when-revealed.py   (after tools/generate-cards.py)
"""
import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
CARDS = ROOT / "frontend" / "public" / "data" / "cards.json"
OUT = ROOT / "src" / "Marvel" / "Card" / "WhenRevealed.hs"
TYPES = {"minion", "side_scheme", "attachment", "environment", "obligation"}

cards = json.loads(CARDS.read_text())["cards"]
# MarvelCDB misspells it on a few cards
ability_label = re.compile(r"<b>\s*When Reve[^<]*(?:</b>\s*:|:\s*</b>)", re.IGNORECASE)
codes = sorted(c["code"] for c in cards if c.get("type") in TYPES and ability_label.search(c.get("text") or ""))
body = "\n".join(f'    {"[" if i == 0 else ","} "{code}"' for i, code in enumerate(codes))
OUT.write_text(f'''-- | Generated by tools/generate-when-revealed.py from the card text: do not edit.
module Marvel.Card.WhenRevealed (hasWhenRevealed) where

import Marvel.Prelude

import Data.HashSet qualified as HashSet
import Marvel.Card.Code

-- | Whether the encounter card (not a treachery, all of which are) has a When Revealed
-- ability.
hasWhenRevealed :: CardCode -> Bool
hasWhenRevealed = (`HashSet.member` codes)

codes :: HashSet CardCode
codes =
  HashSet.fromList
{body}
    ]
''')
print(f"wrote {len(codes)} codes to {OUT}")
