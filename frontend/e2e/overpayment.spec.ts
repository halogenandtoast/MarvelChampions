import { expect, test } from '@playwright/test'

test('payment marks only excess resources and puts the legend below cost covered', async ({ page }) => {
  await page.goto('/#/cards/01001a')
  await page.evaluate(async () => {
    const load = (path: string) => import(/* @vite-ignore */ path)
    const { createApp, h, reactive } = await load('/node_modules/.vite/deps/vue.js')
    const { createI18n } = await load('/node_modules/.vite/deps/vue-i18n.js')
    const { default: PayingTray } = await load('/src/components/PayingTray.vue')
    const { loadLocaleMessages } = await load('/src/locales/messages.ts')
    const { messages } = await loadLocaleMessages('en')
    const cost = reactive({ player: 'payer', card: null, source: null, paid: ['Energy', 'Energy'], owed: [], overpaidResources: [1], anyAmount: false, spent: [] })
    const host = document.createElement('div')
    document.body.replaceChildren(host)
    createApp({ setup: () => () => h(PayingTray, { cost, elsewhere: new Set() }) })
      .use(createI18n({ legacy: false, locale: 'en', messages: { en: messages } })).mount(host)
    Object.assign(window, { paymentPreview: cost })
  })
  const surplus = page.getByRole('status')
  await expect(surplus).toHaveText('* Overpaid')
  await expect(surplus).toHaveAttribute('aria-label', 'Overpaid by 1 resource')
  await expect(page.locator('.paid-resource').nth(0).locator('.overpaid-marker')).toHaveCount(0)
  await expect(page.locator('.paid-resource').nth(1).locator('.overpaid-marker')).toHaveText('*')
  const coveredText = page.getByText('Cost covered', { exact: true })
  const overpaidText = surplus.locator('span').last()
  expect(await overpaidText.evaluate(element => getComputedStyle(element).fontSize)).toBe(await coveredText.evaluate(element => getComputedStyle(element).fontSize))
  expect((await overpaidText.boundingBox())!.x).toBe((await coveredText.boundingBox())!.x)
  expect((await surplus.locator('.status-symbol').boundingBox())!.x).toBe((await page.locator('.owed.done .status-symbol').boundingBox())!.x)
  const covered = (await coveredText.boundingBox())!
  expect((await surplus.boundingBox())!.y).toBeGreaterThanOrEqual(covered.y + covered.height)
  await page.evaluate(() => { Object.assign((window as any).paymentPreview, { paid: ['Energy', 'Physical', 'Energy'], overpaidResources: [0, 2] }) })
  await expect(surplus).toHaveAttribute('aria-label', 'Overpaid by 2 resources')
  await expect(page.locator('.overpaid-marker')).toHaveCount(2)
  await expect(page.locator('.paid-resource').nth(1).locator('.overpaid-marker')).toHaveCount(0)
  await page.evaluate(() => { Object.assign((window as any).paymentPreview, { overpaidResources: [] }) })
  await expect(surplus).toHaveCount(0)
  await page.evaluate(() => { Object.assign((window as any).paymentPreview, { overpaidResources: [0, 2], anyAmount: true }) })
  await expect(surplus).toHaveCount(0)
  await expect(page.locator('.overpaid-marker')).toHaveCount(0)
})
