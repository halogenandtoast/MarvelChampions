module Marvel.Encounter.SpdrNemesisSpec (spec) where

import Data.HashMap.Strict qualified as HashMap
import Marvel.Ability.Types qualified as Ability
import Marvel.Matchers hiding (ExhaustedIdentity, ExhaustedAlly)
import Marvel.Minion.Cards qualified as Minions
import Marvel.Obligation.Cards qualified as Obligations
import Marvel.SideScheme.Cards qualified as Schemes
import Marvel.SideScheme.Types qualified as SideScheme
import Marvel.Treachery.Cards qualified as Treacheries
import TestImport

settle :: GameAppT ()
settle = do
  pressWhenRevealed
  forced <- offers isForced
  if forced then choose "resolve forced ability" isForced >> settle
    else pass >> whenM (offers isForced) settle
 where
  isForced = \case
    UseAbility a -> abilityType a `elem` [Ability.ForcedInterrupt, Ability.ForcedResponse]
    _ -> False

asHero :: IdentityId -> GameAppT ()
asHero p = changeForm p >> pass >> clearHand p

spec :: Spec
spec = describe "SP//dr nemesis" do
  describe "Inherited Burden" do
    it "exhausts Peni Parker and removes the obligation from the game" do
      tg <- testGame ["spdr"]
      let p = player1 tg
      inGame tg do
        _ <- revealNow p Obligations.inheritedBurden
        settle
        isExhaustedNow p `shouldReturn` True
        obligationsInPlay `shouldReturn` 0
        encounterDiscardCodes >>= (`shouldSatisfy` notElem "31025")

    it "can flip from hero to Peni before exhausting her" do
      tg <- testGame ["spdr"]
      let p = player1 tg
      inGame tg do
        asHero p
        _ <- revealNow p Obligations.inheritedBurden
        choose "change to Peni" (isLabel "$label.changeToB")
        settle
        identityMatches AlterEgoIdentity p `shouldReturn` True
        isExhaustedNow p `shouldReturn` True
        obligationsInPlay `shouldReturn` 0

    it "discards a chosen Interface and discards the obligation without exhausting Peni" do
      tg <- testGame ["spdr"]
      let p = player1 tg
      inGame tg do
        interface <- putIntoPlay p "31010"
        _ <- revealNow p Obligations.inheritedBurden
        choose "discard an Interface" (isLabel "$label.discardInterfaceUpgrade")
        choose "discard Host Spider" (isTargetChoice $ upgradeOf interface)
        settle
        upgradesWith "31010" `shouldReturn` []
        isExhaustedNow p `shouldReturn` False
        encounterDiscardCodes >>= (`shouldSatisfy` elem "31025")

    it "does not offer the permanent Pilot as a discardable Interface" do
      tg <- testGame ["spdr"]
      let p = player1 tg
      inGame tg do
        asHero p
        _ <- revealNow p Obligations.inheritedBurden
        choose "stay hero" (isLabel "$label.doNotFlipToAlterEgo")
        offers (isLabel "$label.discardInterfaceUpgrade") `shouldReturn` False
        settle
        upgradesWith "31002b" >>= (`shouldSatisfy` (not . null))

  describe "Giant Monster Attack" do
    it "starts with four fixed threat and crisis even at two players" do
      tg <- testGame ["spdr", "spider-man"]
      inGame tg do
        card <- revealNow (player1 tg) Schemes.giantMonsterAttack
        settle
        sideSchemeThreat (sideSchemeOf card) `shouldReturn` 4
        crisis <- getsGame $ maybe False (SideScheme.sideSchemeCrisis . toAttrs) . HashMap.lookup (sideSchemeOf card) . gameSideSchemes
        crisis `shouldBe` True

    it "charges an energy resource when a hero thwarts it" do
      tg <- testGame ["spider-man"]
      let p = player1 tg
      inGame tg do
        asHero p
        card <- revealNow p Schemes.giantMonsterAttack
        settle
        energy <- putInHand p "01088"
        choose "basic thwart" (isHeroThwart p)
        choose "Giant Monster Attack" (isTargetChoice $ sideSchemeOf card)
        choose "pay energy" (isPayWith energy)
        whenM (offers isFinishPayment) $ choose "finish energy payment" isFinishPayment
        settle
        sideSchemeThreat (sideSchemeOf card) `shouldReturn` 3
        discardOf p >>= (`shouldSatisfy` elem energy)

    it "does not charge for threat removal without a thwart" do
      tg <- testGame ["spdr"]
      let p = player1 tg
      inGame tg do
        card <- revealNow p Schemes.giantMonsterAttack
        settle
        resolve [SideSchemeMessage (sideSchemeOf card) (SideSchemeThreatRemoved GameRef 2)]
        sideSchemeThreat (sideSchemeOf card) `shouldReturn` 2

  describe "M.O.R.B.I.U.S." do
    it "damages the engaged hero for both resources generated by a double-resource card including surplus" do
      tg <- testGame ["spider-man"]
      let p = player1 tg
      inGame tg do
        asHero p
        _ <- addMinion p Minions.morbius
        vest <- putInHand p "01081"
        genius <- putInHand p "01089"
        playWith vest [genius]
        settle
        damageOf p `shouldReturn` 2

    it "does not damage an alter-ego who generates resources" do
      tg <- testGame ["spider-man"]
      let p = player1 tg
      inGame tg do
        clearHand p
        _ <- addMinion p Minions.morbius
        vest <- putInHand p "01081"
        genius <- putInHand p "01089"
        playWith vest [genius]
        settle
        damageOf p `shouldReturn` 0

    it "does not damage another player's hero when that player generates resources" do
      tg <- testGame ["spider-man", "captain-marvel"]
      let p = player1 tg
          other = player2 tg
      inGame tg do
        asHero p
        _ <- addMinion other Minions.morbius
        vest <- putInHand p "01081"
        genius <- putInHand p "01089"
        playOn vest p [genius]
        settle
        damageOf p `shouldReturn` 0
        damageOf other `shouldReturn` 0

  describe "Energy Drain" do
    it "exhausts the alter-ego if energy is unavailable" do
      tg <- testGame ["spdr"]
      let p = player1 tg
      inGame tg do
        clearHand p
        _ <- revealNow p Treacheries.energyDrain
        settle
        isExhaustedNow p `shouldReturn` True
        damageOf p `shouldReturn` 0

    it "lets a hero accept three damage instead of spending resources" do
      tg <- testGame ["spider-man"]
      let p = player1 tg
      inGame tg do
        asHero p
        _ <- revealNow p Treacheries.energyDrain
        settle
        damageOf p `shouldReturn` 3
        isExhaustedNow p `shouldReturn` False

    it "lets a hero spend two energy and avoid damage" do
      tg <- testGame ["spider-man"]
      let p = player1 tg
      inGame tg do
        asHero p
        energy <- putInHand p "01088"
        _ <- revealNow p Treacheries.energyDrain
        choose "spend two energy" (isLabelStarting "$label.spendEnergyResources")
        choose "pay Energy" (isPayWith energy)
        whenM (offers isFinishPayment) $ choose "finish paying" isFinishPayment
        settle
        damageOf p `shouldReturn` 0
        discardOf p >>= (`shouldSatisfy` elem energy)

    it "does not offer exhausting an already exhausted alter-ego" do
      tg <- testGame ["spdr"]
      let p = player1 tg
      inGame tg do
        clearHand p
        resolve [IdentityMessage p ExhaustedIdentity]
        _ <- revealNow p Treacheries.energyDrain
        settle
        damageOf p `shouldReturn` 0
        encounterDiscardCodes >>= (`shouldSatisfy` elem "31028")
