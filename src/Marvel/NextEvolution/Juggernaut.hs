juggernaut :: HasGame m => m (Maybe VillainId)
juggernaut = do
  villains <- selectList AnyVillain
  g <- getGame
  pure $ headMay [vid | vid <- villains, Just def <- [abilityCardDef g $ VillainRef vid], toCardCode def `elem` ["40118", "40119", "40120"]]

juggernautExposed :: HasGame m => m Bool
juggernautExposed = selectAny (AttachmentIs Attachments.ne40122b)

flipJuggernautHelmet :: ReverseQueue m => m ()
flipJuggernautHelmet = do
  helmets <- selectList (AttachmentIs Attachments.ne40122a)
  exposed <- selectList (AttachmentIs Attachments.ne40122b)
  for_ (helmets <> exposed) $ \aid -> cardSpecific aid "flipHelmet" ()

restoreJuggernautHelmet :: ReverseQueue m => m ()
restoreJuggernautHelmet = do
  exposed <- selectList (AttachmentIs Attachments.ne40122b)
  for_ exposed $ \aid -> cardSpecific aid "flipHelmet" ()

juggernautMomentum :: HasGame m => m Natural
juggernautMomentum = maybe (pure 0) getCountersOn =<< juggernaut

-- Cards with conditional damage vulnerability inspect the actual source's
-- printed resource field, not resources generated by one of its abilities.
sourceHasPrintedMental :: HasGame m => Source -> m Bool
sourceHasPrintedMental source = do
  g <- getGame
  pure $ maybe False (elem Mental . printedResources) (abilityCardDef g $ refocus source)

highestCostUpgradeOrSupport :: HasGame m => IdentityId -> m [Target]
highestCostUpgradeOrSupport you = do
  upgrades <- selectList (UpgradeControlledBy $ IdentityWithId you)
  supports <- selectList (SupportControlledBy $ IdentityWithId you)
  g <- getGame
  let ranked = [(toTarget target, fromMaybe 0 $ cdCost def, def) | target <- map toTarget upgrades <> map toTarget supports, Just def <- [abilityCardDef g target]]
  case ranked of
    [] -> pure []
    _ -> do
      let topCost = maximum [n | (_,n,_) <- ranked]
      filterM (fmap (\mods -> CannotBeDiscarded `notElem` mods && CannotLeavePlay `notElem` mods) . getModifiers)
        [target | (target,n,def) <- ranked, n == topCost, Permanent `notElem` cdKeywords def]

leastRemainingAllies :: HasGame m => m [AllyId]
leastRemainingAllies = do
  allies <- selectList AnyAlly
  values <- for allies $ \aid -> (aid,) <$> getCharacterRemainingHitPoints (AllyCharacter aid)
  pure $ case values of
    [] -> []
    _ -> [aid | (aid,hp) <- values, hp == minimum (map snd values)]
