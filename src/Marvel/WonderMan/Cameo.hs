-- Collection choices remain identity-specific even in multi-hero expansion packs.
cameoChoices :: HasGame m => m [CardDef]
cameoChoices = do
  heroes <- getStartingHeroCodes
  pure [def | (ally, hero) <- cameoIdentityPairs, hero `notElem` heroes, Just def <- [lookup ally Allies.allAllies]]

