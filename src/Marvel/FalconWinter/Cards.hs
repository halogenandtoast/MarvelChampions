fwTeamUp :: Text -> Text -> Criteria
fwTeamUp a b = inPlay a <> inPlay b
 where
  inPlay t = AnyCriteria [CharacterExists (IdentityCharacters $ IdentityWithTitle t <> HeroIdentity), AllyExists (AllyNamedAs t)]
