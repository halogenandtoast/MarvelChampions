-- Team-Up requires both named characters in play; alter-egos do not count.
campaignTeamUp :: Text -> Text -> Criteria
campaignTeamUp first second = present first <> present second
 where
  present title = AnyCriteria [CharacterExists (IdentityCharacters $ IdentityWithTitle title <> HeroIdentity), AllyExists (AllyNamedAs title)]
